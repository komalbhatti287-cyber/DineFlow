CREATE OR REPLACE PACKAGE DINEFLOW_PKG AS
 PROCEDURE CREATE_ORDER(P_CUSTOMER_ID NUMBER, P_TABLE_ID NUMBER, P_ITEMS SYS.ODCIVARCHAR2LIST, P_ORDER_ID OUT NUMBER);
 PROCEDURE UPDATE_STATUS(P_ORDER_ID NUMBER, P_STATUS VARCHAR2);
 PROCEDURE GET_BILL(P_ORDER_ID NUMBER, P_SUBTOTAL OUT NUMBER, P_TAX OUT NUMBER, P_TOTAL OUT NUMBER);
 PROCEDURE DASHBOARD(P_ORDERS OUT NUMBER, P_REVENUE OUT NUMBER, P_OCCUPIED OUT NUMBER, P_PENDING OUT NUMBER);
END DINEFLOW_PKG;
/
CREATE OR REPLACE PACKAGE BODY DINEFLOW_PKG AS
 PROCEDURE CREATE_ORDER(P_CUSTOMER_ID NUMBER, P_TABLE_ID NUMBER, P_ITEMS SYS.ODCIVARCHAR2LIST, P_ORDER_ID OUT NUMBER) IS
  V_STATUS VARCHAR2(12); V_ID NUMBER; V_QTY NUMBER; V_PRICE NUMBER;
 BEGIN
  SELECT TABLE_STATUS INTO V_STATUS FROM DF_TABLES WHERE TABLE_ID=P_TABLE_ID FOR UPDATE;
  IF V_STATUS='OCCUPIED' THEN RAISE_APPLICATION_ERROR(-20001,'Table is already occupied'); END IF;
  IF P_ITEMS IS NULL OR P_ITEMS.COUNT=0 THEN RAISE_APPLICATION_ERROR(-20002,'Add at least one menu item'); END IF;
  INSERT INTO DF_ORDERS(CUSTOMER_ID,TABLE_ID) VALUES(P_CUSTOMER_ID,P_TABLE_ID) RETURNING ORDER_ID INTO P_ORDER_ID;
  FOR I IN 1..P_ITEMS.COUNT LOOP
   V_ID:=TO_NUMBER(REGEXP_SUBSTR(P_ITEMS(I),'[^:]+',1,1)); V_QTY:=TO_NUMBER(REGEXP_SUBSTR(P_ITEMS(I),'[^:]+',1,2));
   SELECT PRICE INTO V_PRICE FROM DF_MENU WHERE ITEM_ID=V_ID AND IS_AVAILABLE='Y';
   IF V_QTY<1 THEN RAISE_APPLICATION_ERROR(-20003,'Quantity must be positive'); END IF;
   INSERT INTO DF_ORDER_ITEMS(ORDER_ID,ITEM_ID,QUANTITY,UNIT_PRICE) VALUES(P_ORDER_ID,V_ID,V_QTY,V_PRICE);
  END LOOP;
  UPDATE DF_TABLES SET TABLE_STATUS='OCCUPIED' WHERE TABLE_ID=P_TABLE_ID;
 END;
 PROCEDURE UPDATE_STATUS(P_ORDER_ID NUMBER,P_STATUS VARCHAR2) IS V_TABLE NUMBER;
 BEGIN
  IF P_STATUS NOT IN ('PLACED','PREPARING','SERVED','CANCELLED') THEN RAISE_APPLICATION_ERROR(-20004,'Invalid status'); END IF;
  SELECT TABLE_ID INTO V_TABLE FROM DF_ORDERS WHERE ORDER_ID=P_ORDER_ID;
  UPDATE DF_ORDERS SET ORDER_STATUS=P_STATUS WHERE ORDER_ID=P_ORDER_ID;
  IF P_STATUS IN ('SERVED','CANCELLED') THEN UPDATE DF_TABLES SET TABLE_STATUS='AVAILABLE' WHERE TABLE_ID=V_TABLE; END IF;
 END;
 PROCEDURE GET_BILL(P_ORDER_ID NUMBER,P_SUBTOTAL OUT NUMBER,P_TAX OUT NUMBER,P_TOTAL OUT NUMBER) IS
 BEGIN
  SELECT NVL(SUM(QUANTITY*UNIT_PRICE),0) INTO P_SUBTOTAL FROM DF_ORDER_ITEMS WHERE ORDER_ID=P_ORDER_ID;
  P_TAX:=ROUND(P_SUBTOTAL*0.05,2); P_TOTAL:=P_SUBTOTAL+P_TAX;
 END;
 PROCEDURE DASHBOARD(P_ORDERS OUT NUMBER,P_REVENUE OUT NUMBER,P_OCCUPIED OUT NUMBER,P_PENDING OUT NUMBER) IS
 BEGIN
  SELECT COUNT(*) INTO P_ORDERS FROM DF_ORDERS WHERE TRUNC(ORDER_DATE)=TRUNC(SYSDATE);
  SELECT NVL(SUM(I.QUANTITY*I.UNIT_PRICE),0) INTO P_REVENUE FROM DF_ORDERS O JOIN DF_ORDER_ITEMS I ON I.ORDER_ID=O.ORDER_ID WHERE TRUNC(O.ORDER_DATE)=TRUNC(SYSDATE) AND O.ORDER_STATUS<>'CANCELLED';
  SELECT COUNT(*) INTO P_OCCUPIED FROM DF_TABLES WHERE TABLE_STATUS='OCCUPIED';
  SELECT COUNT(*) INTO P_PENDING FROM DF_ORDERS WHERE ORDER_STATUS IN ('PLACED','PREPARING');
 END;
END DINEFLOW_PKG;
